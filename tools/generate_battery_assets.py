"""Charging bolt for the battery icon, as ALPHA_8BIT masks for LVGL.

Body, tip and fill are plain LVGL objects; only the bolt needs an image.
It is drawn at 8x and scaled down for antialiasing. Needs Pillow.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
SIZE = (12, 16)
# Coordinates relative to the (234, 457) corner on screen.
BOLT = [(6.6, 1.2), (1.0, 8.6), (4.6, 8.6), (3.4, 13.8), (9.0, 6.4), (5.4, 6.4)]


def mask(grow=0.0):
    scale = 8
    img = Image.new('L', (SIZE[0] * scale, SIZE[1] * scale))
    ImageDraw.Draw(img).polygon([(x * scale, y * scale) for x, y in BOLT], fill=255)
    if grow:
        # Dark outline so the bolt stands out from the fill and the body.
        img = img.filter(ImageFilter.MaxFilter(2 * round(grow * scale) + 1))
    return img.resize(SIZE, Image.Resampling.LANCZOS)


def header(name, img):
    data = img.tobytes()
    text = f'static const uint8_t {name}_pixels[] = {{\n'
    text += '\n'.join('  ' + ','.join(map(str, data[i:i + 24])) + ',' for i in range(0, len(data), 24))
    text += f'\n}};\nstatic const lv_img_dsc_t {name} = {{\n'
    text += f'  .header={{.cf=LV_IMG_CF_ALPHA_8BIT, .w={img.width}, .h={img.height}}},\n'
    return text + f'  .data_size=sizeof {name}_pixels, .data={name}_pixels\n}};\n'


def main():
    text = '/* Generated by tools/generate_battery_assets.py, do not edit. */\n#pragma once\n#include "lvgl.h"\n'
    text += header('panel_bolt_outline', mask(1.1)) + header('panel_bolt', mask())
    (ROOT / 'firmware/main/battery_assets.h').write_text(text, encoding='utf-8')
    print('battery_assets.h: bolt and outline, ALPHA_8BIT 12x16')


if __name__ == '__main__':
    main()
