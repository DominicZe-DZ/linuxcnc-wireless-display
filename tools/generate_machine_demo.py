"""Writes an air-cutting demo program that exercises everything the display
shows: XYZ motion, feed, spindle speeds and coolant. It only writes a file,
it never connects to LinuxCNC.

Every G1 moves X, Y and Z together along a closed path (cos, sin and sin of
the double angle), always inside the box you ask for. The program is fully
explicit so you can check it in the LinuxCNC preview before running it.
"""
import argparse
import json
import math
from pathlib import Path


def make_program(half_x, half_y, half_z, feed=500, cycles=4):
    if any(not math.isfinite(v) or v<=0 for v in (half_x,half_y,half_z,feed)):
        raise ValueError('travel and feed must be positive and finite')
    if not 1<=cycles<=20 or feed>1000:
        raise ValueError('the demo is limited to 1-20 cycles and 1000 mm/min')
    lines=[
        '(WIRELESS DISPLAY DEMO - AIR CUTTING ONLY)',
        '(Generated by tools/generate_machine_demo.py. G54 is not changed.)',
        f'(Travel around G54: X +/-{half_x:g} Y +/-{half_y:g} Z +/-{half_z:g} mm.)',
        f'(Feed {feed:g} mm/min, {cycles} cycles, spindle 1000-2500-5000-0 RPM.)',
        '(Check the free volume and the preview before running.)',
        '(No G92 offset, tool length offset checked.)',
        'G21 G17 G90 G94 G54 G40 G80',
        'G64 P0.05',
        'M5', 'S0', 'M9',
        '(Approach at feed rate, Z first, then XY.)',
        f'G1 Z{half_z:.3f} F{feed:g}',
        'G1 X0.000 Y0.000',
        f'G1 X{half_x:.3f} Y0.000 Z0.000',
    ]
    points=[(half_x,0.0,0.0)]
    length=0.0
    for cycle in range(1,cycles+1):
        lines += [f'(CYCLE {cycle}/{cycles} - SPINDLE 1000 RPM, COOLANT OFF)',
                  'M3 S1000','M9']
        previous=(half_x,0.0,0.0)
        for degrees in range(5,361,5):
            if degrees==90:
                lines += ['(2500 RPM - FLOOD M8)','S2500','M8']
            elif degrees==180:
                lines += ['(5000 RPM - MIST ONLY M7)','S5000','M9','M7']
            elif degrees==270:
                lines += ['(5000 RPM - FLOOD AND MIST)','M8']
            radians=math.radians(degrees)
            point=tuple(round(v,3) for v in (half_x*math.cos(radians),half_y*math.sin(radians),half_z*math.sin(2*radians)))
            # avoid printing -0.000 at the zero crossings
            point=tuple(0.0 if abs(v)<.0005 else v for v in point)
            lines.append('G1 X%.3f Y%.3f Z%.3f'%point)
            length+=math.dist(previous,point)
            previous=point
            points.append(point)
        lines += ['(SPINDLE DOWN TO ZERO, 5 S DWELL COVERS THE RAMP)',
                  'M5','S0','M9','G4 P5']
    lines += ['(END: UP TO THE TOP OF THE BOX AND BACK TO XY ZERO)',
              f'G1 Z{half_z:.3f} F{feed:g}','G1 X0.000 Y0.000','M5','S0','M9','M2']
    report={
        'coordinate_system':'G54','units':'mm','feed_mm_min':feed,'cycles':cycles,
        'envelope':{'x':[-half_x,half_x],'y':[-half_y,half_y],'z':[-half_z,half_z]},
        'spindle_rpm':[1000,2500,5000,0], 'coolant':['off','flood','mist','flood+mist','off'],
        'coordinated_segments':len(points)-1,'curve_length_mm':round(length,3),
        'minimum_curve_and_stop_seconds':round(length/feed*60+5*cycles,1),
        'executed':False,
    }
    return '\n'.join(lines)+'\n',report


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--half-x',type=float,required=True)
    parser.add_argument('--half-y',type=float,required=True)
    parser.add_argument('--half-z',type=float,required=True)
    parser.add_argument('--feed',type=float,default=500)
    parser.add_argument('--cycles',type=int,default=4)
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args()
    program,report=make_program(args.half_x,args.half_y,args.half_z,args.feed,args.cycles)
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(program,encoding='ascii')
    args.output.with_suffix('.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    print(f'G-code written (nothing was run): {args.output}')


if __name__=='__main__':main()
