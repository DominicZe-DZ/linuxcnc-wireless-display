"""Image assets for the Classic gauge: logos, indicators and the needle with
its pre-rendered glow (firmware/main/dashboard_assets.h).

Only small images are stored. The dial, labels and values are LVGL objects
drawn with partial refresh. Needs Pillow and the Node module sharp; the
generated header is committed so the firmware build needs neither.
"""
import base64
from io import BytesIO
import json
import os
from pathlib import Path
import subprocess
import xml.etree.ElementTree as ET
from PIL import Image, ImageDraw, ImageFilter
from svg_assets import ROOT, el, rgba_logo, status_icon, wordmark


def header_image(name, img, color=False):
    img = img.convert('RGBA')
    width, height = img.size
    data = bytearray()
    if color:
        # RGB565 little endian + alpha: LVGL 8 TRUE_COLOR_ALPHA at 16 bpp.
        for r, g, b, a in img.getdata():
            pixel = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            data.extend((pixel & 255, pixel >> 8, a))
    else:
        data.extend(img.getchannel('A').tobytes())
    text = f'static const uint8_t {name}_pixels[] = {{\n'
    text += '\n'.join('  '+','.join(map(str,data[i:i+32]))+',' for i in range(0,len(data),32))
    fmt = 'LV_IMG_CF_TRUE_COLOR_ALPHA' if color else 'LV_IMG_CF_ALPHA_8BIT'
    text += f'\n}};\nstatic const lv_img_dsc_t {name} = {{\n'
    text += f'  .header={{.cf={fmt}, .w={width}, .h={height}}},\n'
    return text + f'  .data_size=sizeof {name}_pixels, .data={name}_pixels\n}};\n'


def needle_image():
    scale = 4
    size = (256*scale,40*scale)
    outline = [(8,16),(22,15),(240,20),(22,25),(8,24)]
    body = Image.new('RGBA',size)
    ImageDraw.Draw(body).polygon([(x*scale,y*scale) for x,y in outline],fill='#ff7800')
    halo = body.filter(ImageFilter.GaussianBlur(2.4*scale))
    halo.putalpha(halo.getchannel('A').point(lambda p:round(p*.65)))
    img = Image.alpha_composite(halo,body)
    core = Image.new('RGBA',size)
    ImageDraw.Draw(core).polygon([(22*scale,18*scale),(240*scale,20*scale),(22*scale,22*scale)],fill=(255,226,160,230))
    return Image.alpha_composite(img,core).resize((256,40),Image.Resampling.LANCZOS)


def main():
    jobs=[]
    for name, resource, width, height in [('panel_emco','emco.svg',72,33),('panel_model','f1-cnc.svg',84,31)]:
        svg=el('svg',width=width,height=height,viewBox=f'0 0 {width} {height}')
        svg.append(wordmark(resource,0,0,width,height,'white'))
        jobs.append(dict(name=name,svg=ET.tostring(svg,encoding='unicode'),width=width,height=height))
    for kind in ('spindle','coolant'):
        svg=el('svg',width=32,height=32,viewBox='0 0 32 32')
        icon=status_icon(kind)
        icon.set('color','white')
        svg.append(icon)
        jobs.append(dict(name=f'panel_{kind}_icon',svg=ET.tostring(svg,encoding='unicode'),width=32,height=32))
    env=dict(os.environ)
    local=ROOT/'.cache/dashboard-tools/node_modules'
    if local.exists():env['NODE_PATH']=str(local)
    rendered=subprocess.run(['node',str(ROOT/'tools/render_dashboard_vectors.cjs')],input=json.dumps(jobs),text=True,capture_output=True,check=True,env=env)
    text='/* Generated by tools/generate_dashboard_assets.py, do not edit. */\n#pragma once\n#include "lvgl.h"\n'
    brand=Image.open(BytesIO(base64.b64decode(rgba_logo(stacked=True)))).resize((140,101),Image.Resampling.LANCZOS)
    text+=header_image('panel_brand',brand)
    for item in json.loads(rendered.stdout):
        text+=header_image(item['name'],Image.open(BytesIO(base64.b64decode(item['png']))))
    text+=header_image('panel_needle',needle_image(),color=True)
    (ROOT/'firmware/main/dashboard_assets.h').write_text(text,encoding='utf-8')
    print('dashboard_assets.h: logo 140x101, EMCO and F1-CNC marks, two indicators, needle 256x40')


if __name__=='__main__':main()
