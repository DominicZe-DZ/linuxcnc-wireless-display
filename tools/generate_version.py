"""Writes firmware/main/version.h with the build ID (short commit hash).

Run it before idf.py build, locally and in CI. The IDF container has no git,
so there the event SHA is used. An image built with the "nobuildid" placeholder
always looks outdated and the display would try to update to itself on every
boot, so in CI that is an error.
"""
import os
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]


def build_id(run, env, warn=None):
    """Short ID: git, then GITHUB_SHA, then error in CI / placeholder locally."""
    if warn is None:
        def warn(message):
            print(message, file=sys.stderr)
    sha = ''
    try:
        sha = run(['git', 'rev-parse', '--short=7', 'HEAD'], cwd=REPO,
                  capture_output=True, text=True, check=True).stdout.strip()
    except Exception as exc:  # noqa: BLE001 no git (CI container)
        sha = env.get('GITHUB_SHA', '')[:7]
        if sha:
            warn(f'warning: no git ({exc}), using GITHUB_SHA')
    if not sha:
        if env.get('GITHUB_ACTIONS') == 'true':
            raise SystemExit('no build ID in CI (no git and no GITHUB_SHA)')
        warn('warning: no git and no GITHUB_SHA, using a placeholder build ID')
        sha = 'nobuildid'
    if len(sha) > 16:
        raise SystemExit('build ID too long')
    return sha


def main():
    sha = build_id(subprocess.run, os.environ)
    target = REPO / 'firmware/main/version.h'
    target.write_text(
        '/* Generated by tools/generate_version.py, do not edit. */\n'
        f'#define PANEL_BUILD_ID "{sha}"\n', encoding='utf-8')
    print(f'version.h: PANEL_BUILD_ID "{sha}"')


if __name__ == '__main__':
    main()
