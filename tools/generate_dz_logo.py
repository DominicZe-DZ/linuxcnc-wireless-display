"""Turns the DominicZe logo into the LVGL alpha mask used on the DRO/Spindle
pages (firmware/main/dz_logo.h).

The source PNG is white on black RGB, not RGBA, so luminance is used as the
coverage. The gear, the name and the tag line are cropped from the original
and laid out side by side; nothing is redrawn. Needs Pillow.
"""
from pathlib import Path
from PIL import Image, ImageChops, ImageOps

ROOT = Path(__file__).resolve().parents[1]


def main():
    original = Image.open(ROOT / "assets/dz-original.png")
    alpha = ImageOps.grayscale(original.convert("RGB"))
    if "A" in original.getbands():
        alpha = ImageChops.multiply(alpha, original.getchannel("A"))
    if alpha.point(lambda x: 255 if x > 32 else 0).getbbox() is None:
        raise ValueError("the logo has no visible strokes")
    # Horizontal layout: gear on the left, the two text lines on the right.
    width, height = 190, 40
    parts = [
        {'bbox': [541, 220, 971, 612], 'target': [0, 0, 44, 40]},
        {'bbox': [448, 628, 1022, 736], 'target': [52, 0, 138, 26]},
        {'bbox': [448, 752, 1022, 792], 'target': [52, 29, 138, 10]},
    ]
    horizontal = Image.new('L', (width, height), 0)
    for part in parts:
        x, y, w, h = part['target']
        tile = alpha.crop(tuple(part['bbox'])).resize((w, h), Image.Resampling.LANCZOS)
        horizontal.paste(tile, (x, y))
    # Same mask as a transparent PNG, handy for docs and mock-ups.
    preview = Image.new('RGBA', (width, height), 'white')
    preview.putalpha(horizontal)
    preview.save(ROOT / 'assets/dz-horizontal.png')
    data = list(horizontal.tobytes())
    text = '/* Generated by tools/generate_dz_logo.py from assets/dz-original.png, do not edit. */\n'
    text += '#pragma once\n#include "lvgl.h"\n'
    text += 'static const uint8_t dz_pixels[] = {\n'
    text += '\n'.join('  ' + ','.join(map(str, data[i:i+32])) + ',' for i in range(0, len(data), 32))
    text += '\n};\nstatic const lv_img_dsc_t dz_logo = {\n'
    text += f'  .header = {{.cf=LV_IMG_CF_ALPHA_8BIT, .w={width}, .h={height}}},\n'
    text += '  .data_size=sizeof dz_pixels, .data=dz_pixels\n};\n'
    (ROOT / 'firmware/main/dz_logo.h').write_text(text, encoding='utf-8')
    print(f'dz_logo.h: {width} x {height} mask')


if __name__ == '__main__':
    main()
