"""Scales the logo masks down for the DRO and Spindle page headers.

LVGL 8 can't zoom ALPHA_8BIT images, so they are stored at final size.
Needs Pillow.
"""
from pathlib import Path
import re
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / 'firmware/main/dashboard_assets.h').read_text()
output = '/* Generated by tools/generate_header_assets.py, do not edit. */\n#pragma once\n#include "lvgl.h"\n'
for name, original, target in [('emco',(72,33),(46,21)), ('model',(84,31),(59,22))]:
    match = re.search(r'panel_' + name + r'_pixels\[\]\s*=\s*\{([^}]+)\}',source)
    if not match:
        raise ValueError('mask not found: ' + name)
    pixels = bytes(int(value) for value in re.findall(r'\d+',match[1]))
    mask = Image.frombytes('L',original,pixels).resize(target,Image.Resampling.LANCZOS)
    symbol = 'page_' + name
    output += f'static const uint8_t {symbol}_pixels[] = {{\n'
    data = mask.tobytes()
    output += '\n'.join('  ' + ','.join(map(str,data[i:i+24])) + ',' for i in range(0,len(data),24))
    output += f'\n}};\nstatic const lv_img_dsc_t {symbol} = {{\n'
    output += f' .header={{.cf=LV_IMG_CF_ALPHA_8BIT,.w={target[0]},.h={target[1]}}},\n'
    output += f' .data_size=sizeof {symbol}_pixels,.data={symbol}_pixels\n}};\n'
(ROOT / 'firmware/main/header_assets.h').write_text(output)
print('header masks written: EMCO 46x21, F1-CNC 59x22')
